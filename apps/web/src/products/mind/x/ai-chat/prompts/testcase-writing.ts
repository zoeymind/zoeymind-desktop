export const testcaseWriting = (): string => `# 编写规范

说明：字段校验以工具 Schema 为准（例如优先级前缀、步骤分隔符等）。本节聚焦可读性与可执行性。

## 用例名称格式
**格式：\`[P优先级]对象-动作 & 前置条件\`**

- \`[P1]\`：核心功能、主流程。
- \`[P2]\`：边界、异常、负向测试。
- \`[P3]\`：UI细节、体验优化。
- \`& 前置条件\`：当用例依赖特定状态时必须写明（如需要登录、特定角色、先完成某操作、特定数据条件等）。无特殊前提时省略。

示例：
- \`[P1]手机号输入框-输入合法号码\`
- \`[P1]图片上传按钮-选择9张图片 & 已登录\`
- \`[P2]搜索输入框-输入超长文本 & 位于首页\`
- \`[P2]提交按钮-快速连续点击 & 商品库存为1\`

## 步骤格式
**每一步：\`操作 & 预期结果\`**

### 操作要具体
写清楚**在哪里、做什么、用什么数据**，让执行者不用猜。
- ✅ \`在昵称输入框输入 51 个字符 & 输入被截断为 50 个字符，显示字数限制提示\`
- ❌ \`输入超长内容 & 有提示\`（多长？哪个输入框？什么提示？）

### 预期结果要可验证
描述**具体的、可观察的变化**，不要用模糊词。
- ✅ \`点击保存 & 弹窗关闭，列表页新增一条记录，顶部显示"保存成功"提示 3 秒后消失\`
- ❌ \`点击保存 & 保存成功\`（怎么判断成功？页面有什么变化？）

### 一步只做一件事
每步聚焦单一操作，不要把多个操作合并到一步。
- ✅ \`输入手机号 13800000000 & 输入框正常显示\` → \`点击获取验证码 & 按钮变为 60 秒倒计时\`
- ❌ \`输入手机号并点击获取验证码 & 收到短信\`（两个操作混在一步）

## 颗粒度控制
- **单一职责**：一条用例验证一个行为点。如果一条用例需要分支讨论"如果…则…"，说明应该拆成多条。
- **适度合并**：同一元素的纯 UI 校验（如占位符文案、禁用态样式）可合并为一条 P3 用例。
- **避免重复**：多个模块都需要验证的通用逻辑（如"未登录跳转"），在最顶层界面模块写一次，子模块不重复。

## 优先级策略
- **P1 占比 ≥ 40%**：核心主流程必须充分覆盖。
- **P2 占比 ≈ 40%**：边界、异常、安全等场景。
- **P3 占比 ≤ 20%**：UI 细节、体验优化。
- 分配优先级时，想象该用例如果失败，对用户影响有多大：阻断 → P1、降级 → P2、体验 → P3。
`
