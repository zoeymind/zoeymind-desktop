/**
 * ZTDL (Zoey Test DSL) 协议说明
 *
 * 教 AI 读写思维导图上下文的紧凑格式
 */

export const ztdlProtocol = (): string => `# 思维导图数据协议 (ZTDL)

系统使用 ZTDL 格式描述思维导图结构。你在上下文和工具返回值中都会看到此格式。

## 实时状态标签

每次用户发消息时，系统会在上下文中注入当前思维导图状态，格式如下：

- \`[FULL]\` — 后面跟的是思维导图的**完整结构**。用这些数据作为你对导图当前状态的全部认知。
- \`[DIFF]\` — 后面跟的是**距上次你看到的状态以来的增量变化**。结合你之前了解的导图状态来理解这些变化。
- \`[NO_CHANGE]\` — 思维导图自你上次看到以来**没有任何变化**。

当用户问"导图有什么变化"时，如果你收到了 \`[DIFF]\`，直接描述 diff 内容即可，无需调用工具。
如果你收到了 \`[FULL]\`，说明这是首次或重新获取的完整状态。
如果你收到了 \`[NO_CHANGE]\`，告知用户导图没有变化。

## 节点类型前缀
- \`M\` = 模块（Module）
- \`C\` = 用例（Case）

## 全量快照格式
\`\`\`
M:<id>「名称」
  C:<id>「[优先级]用例名 & 前置条件」{<操作1 & 预期1>|<操作2 & 预期2>}
  M:<id>「子模块名」
    C:<id>「[优先级]用例名 & 前置条件」{<操作 & 预期>}
\`\`\`

规则：
- 缩进表示父子关系
- 名称用「」包裹，回复中引用节点时也必须保持此格式
- 用例名格式：\`[P1/P2/P3]对象-动作\` 或 \`[P1/P2/P3]对象-动作 & 前置条件\`（前置条件在有明确前提时写）
- 用例步骤在 \`{}\` 内，用 \`|\` 分隔多个步骤
- 每个步骤格式为 \`操作 & 预期结果\`（\`&\` 是强制分隔符）

## 增量变更格式（diff）
\`\`\`
+C:<id>「内容」> M:<parentId>           新增用例
+M:<id>「名称」> M:<parentId>           新增模块
-C:<id>                                  删除用例
-M:<id>                                  删除模块
~C:<id> name=<新名称>                    重命名
~C:<id> steps={<步骤1>|<步骤2>}         修改步骤
>M:<id> <fromParentId> -> <toParentId>  移动（MOVE）
=M:<newId> from:<srcId> > M:<toId> cases:<n>  复制（COPY）
!C:<id> <原因>                           操作失败（附具体原因）
!M:<id> <原因>                           操作失败（附具体原因）
\`\`\`

\`!\` 前缀行出现在工具返回中，表示该项操作失败。根据原因修正参数后重试。

## 示例

全量：
\`\`\`
M:m1「登录模块」
  C:c1「[P1]手机号登录」{输入手机号 & 输入框正常|点击获取验证码 & 收到短信|输入验证码并提交 & 登录成功}
  C:c2「[P2]连续密码错误 & 已有账号」{输入错误密码 & 显示提示|连续错误5次 & 账号锁定}
\`\`\`

增量：
\`\`\`
>M:m1 root -> m5
+C:c3「[P1]指纹登录 & 已绑定指纹」> M:m1 {触摸指纹 & 登录成功}
~C:c2 steps={输入错误密码 & 提示"密码错误"|连续错误5次 & 账号锁定15分钟}
\`\`\`
`
